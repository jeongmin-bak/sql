ALTER TABLE DEPT ADD SUMSAL NUMBER(10);

SELECT DEPTNO, SUM(SAL)
FROM EMP
GROUP BY DEPTNO;

MERGE INTO DEPT d
USING ( SELECT DEPTNO, SUM(SAL) AS SUMSAL
        FROM EMP
        GROUP BY DEPTNO
        ) v
ON (d.DEPTNO=v.DEPTNO)
WHEN MATCHED THEN
    UPDATE SET d.SUMSAL = v.SUMSAL;

SELECT *
FROM DEPT;


